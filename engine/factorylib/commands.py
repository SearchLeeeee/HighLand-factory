MARKER = "<!-- GENERATED by HighLand-factory {version} from {source}; do not hand-edit. -->"


def _now() -> str:
    return datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")


def _load_answers(path: str | None) -> dict[str, Any]:
    if not path:
        return {}
    data = util.load_yaml_file(Path(path).expanduser().resolve())
    if not isinstance(data, dict):
        raise util.FactoryError("answers file must contain a YAML mapping")
    return data


def _pin_factory_version() -> str:
    version = util.factory_version()
    parts = version.split(".")
    try:
        major, minor = int(parts[0]), int(parts[1])
    except (IndexError, ValueError):
        return ">=0.1.0 <0.2.0"
    return f">={version} <{major}.{minor + 1}.0"


def _build_local(python: str | None) -> dict[str, Any]:
    interpreter = Path(python).expanduser().resolve() if python else Path(sys.executable)
    return {
        "factory_root": str(util.FACTORY_ROOT),
        "python": str(interpreter),
        "node": None,
        "ports": {},
        "env": {},
        "platform": platform.system().lower(),
        "created_at": _now(),
    }


def _normalize_wiki_paths(config: dict[str, Any]) -> None:
    """Keep verification paths consistent with a custom wiki folder name."""
    repo = config.get("repo") or {}
    wiki_path = str(repo.get("wiki_path") or "wiki").strip("/")
    if not wiki_path or wiki_path == "wiki":
        return
    verification = config.setdefault("verification", {})
    for key in ("baseline_evidence", "evidence_root"):
        value = verification.get(key)
        if isinstance(value, str) and value.startswith("wiki/"):
            verification[key] = wiki_path + value[len("wiki"):]


def _apply_identity(config: dict[str, Any], work: Path) -> None:
    project = config.setdefault("project", {})
    if not str(project.get("name") or "").strip():
        project["name"] = work.name
    if not str(project.get("slug") or "").strip():
        project["slug"] = util.slugify(str(project.get("name") or work.name))
    factory = config.setdefault("factory", {})
    if not str(factory.get("version") or "").strip():
        factory["version"] = _pin_factory_version()
    factory.setdefault("template", "workspace-v1")


def _is_within(path: Path, parent: Path) -> bool:
    try:
        path.resolve().relative_to(parent.resolve())
        return True
    except ValueError:
        return False


def _apply_repo_topology(config: dict[str, Any], work: Path, code: str | None, wiki: str | None) -> None:
    repo = config.setdefault("repo", {})
    if code:
        code_path = Path(code).expanduser().resolve()
        if not code_path.exists():
            raise util.FactoryError(f"--code path does not exist: {code_path}")
        if _is_within(code_path, work):
            repo["mode"] = "mono"
            repo["code_path"] = code_path.relative_to(work.resolve()).as_posix()
            repo["code_external"] = None
        else:
            repo["mode"] = "split"
            repo["code_external"] = str(code_path)
    if wiki:
        wiki_path = Path(wiki).expanduser()
        if wiki_path.is_absolute():
            if not _is_within(wiki_path, work):
                raise util.FactoryError("--wiki must be inside the work repo")
            repo["wiki_path"] = wiki_path.resolve().relative_to(work.resolve()).as_posix()
        else:
            repo["wiki_path"] = wiki_path.as_posix()


def _detect_wiki_path(work: Path, explicit: str | None) -> str:
    if explicit:
        return explicit
    for candidate in ("wiki", "docs"):
        if (work / candidate).is_dir():
            return candidate
    return "wiki"


def _print_plan(plan: Plan, as_json: bool) -> None:
    if as_json:
        util.print_json(plan.as_dict())
        return
    counts = plan.counts()
    print(f"Work: {plan.work}")
    print(f"Plan: {counts.get('create', 0)} create, {counts.get('overwrite', 0)} overwrite, {counts.get('skip', 0)} skip")
    for item in plan.files:
        if item.action == "skip":
            continue
        print(f"  {item.action.upper():9} {item.rel}" + (f"  ({item.reason})" if item.reason else ""))
    skipped = [item for item in plan.files if item.action == "skip"]
    if skipped:
        print("Skipped (already exist, not overwritten):")
        for item in skipped:
            print(f"  SKIP      {item.rel}  ({item.reason})")


def _write_marker_file(path: Path, source: str, body: str) -> None:
    header = MARKER.format(version=util.factory_version(), source=source)
    util.write_text(path, header + "\n\n" + body.rstrip() + "\n")


def _write_init_record(
    layout: Layout,
    config: dict[str, Any],
    *,
    mode: str,
    answers: dict[str, Any],
    hashes: dict[str, str],
    skipped: list[str],
) -> None:
    lines = [
        "# Init Record",
        "",
        "This file is the provenance baseline for the work repo initialization.",
        "",
        "## Run",
        "",
        f"- mode: `{mode}`",
        f"- date: `{_now()}`",
        f"- factory: `HighLand-factory {util.factory_version()}` at `{util.FACTORY_ROOT}`",
        f"- engine python: `{layout.python}`",
        f"- repo mode: `{(config.get('repo') or {}).get('mode')}`",
        "",
        "## Effective configuration",
        "",
        "```yaml",
        util.dump_yaml(config).rstrip(),
        "```",
        "",
        "## Answers supplied at init",
        "",
        "```yaml",
        util.dump_yaml(answers).rstrip() if answers else "{}",
        "```",
        "",
        "## Assumptions",
        "",
        "- Values not present in the answers file came from factory defaults; review `.factory/factory.yaml` before implementation.",
        "- Owner paths and commands are placeholders until the project fills them in.",
        "- The first generated owner profiles are starting points; later edits are project-owned.",
        "",
        "## Generated files",
        "",
        "| path | sha256 |",
        "| --- | --- |",
    ]
    for rel in sorted(hashes):
        lines.append(f"| `{rel}` | `{hashes[rel]}` |")
    if not hashes:
        lines.append("| _none_ | _n/a_ |")
    if skipped:
        lines.extend(["", "## Skipped existing files", "", "These files already existed and were not modified:"])
        lines.extend(f"- `{rel}`" for rel in skipped)
    lines.extend(
        [
            "",
            "## Next steps",
            "",
            "1. Run `factory doctor --work .` and fix every failure.",
            "2. Execute the configured commands once and record the green baseline in the baseline evidence file.",
            "3. Initialize git (if needed) and make the first commit only after the doctor passes.",
            "4. Start the first change with `$hl-feasibility-grill` (or `$hl-quick-change` for a bounded fix).",
            "",
        ]
    )
    _write_marker_file(layout.init_record, "engine/init-record", "\n".join(lines))


def _write_baseline(layout: Layout, config: dict[str, Any]) -> None:
    if layout.baseline_evidence.exists():
        return
    commands = config.get("commands") or {}
    lines = [
        "# Init Baseline",
        "",
        "Status: pending",
        "",
        "Record the first successful run of every configured command here, with date, environment and result.",
        "",
        "| action | command | expected | observed |",
        "| --- | --- | --- | --- |",
    ]
    for key in ("build", "lint", "typecheck", "test", "e2e", "verify"):
        for command in commands.get(key) or []:
            lines.append(f"| {key} | `{command}` | pass | _pending_ |")
    if len(lines) == 6:
        lines.append("| _none configured_ | - | - | - |")
    lines.extend(
        [
            "",
            "When every row passes, change `Status: pending` to `Status: passed`.",
            "",
        ]
    )
    _write_marker_file(layout.baseline_evidence, "engine/init-baseline", "\n".join(lines))


def _write_state(layout: Layout, config: dict[str, Any], *, mode: str, hashes: dict[str, str]) -> None:
    state = config_mod.load_state(layout.work)
    profile_hash = util.sha256_file(layout.workflow_profile) if layout.workflow_profile.is_file() else ""
    state.update(
        {
            "schema": 1,
            "factory_version": util.factory_version(),
            "template": (config.get("factory") or {}).get("template", "workspace-v1"),
            "mode": mode,
            "updated_at": _now(),
            "config_hash": config_mod.config_hash(config),
            "profile_hash": profile_hash,
            "generated_files": {**state.get("generated_files", {}), **hashes},
        }
    )
    state.setdefault("created_at", _now())
    config_mod.save_state(layout.work, state)


GITIGNORE_BLOCK = """
# --- HighLand-factory machine state (never commit) ---
.factory/local.yaml
.factory/state.json
.factory/.venv/
.factory-cache/
"""


def _ensure_gitignore(work: Path) -> bool:
    path = work / ".gitignore"
    existing = path.read_text(encoding="utf-8-sig") if path.is_file() else ""
    required = [".factory/local.yaml", ".factory/state.json"]
    missing = [item for item in required if item not in existing]
    if not missing:
        return False
    text = existing.rstrip() + "\n" + GITIGNORE_BLOCK
    util.write_text(path, text)
    return True


def _wiki_orphans(layout: Layout) -> list[str]:
    script = layout.factory_root / "skills" / "hl-wiki-merge" / "scripts" / "validate_llm_wiki.py"
    if not script.is_file() or not layout.wiki.is_dir():
        return []
    try:
        completed = subprocess.run(
            [str(layout.python), str(script), "--wiki-root", str(layout.wiki), "--format", "json"],
            capture_output=True,
            text=True,
            timeout=180,
        )
    except (OSError, subprocess.SubprocessError):
        return []
    try:
        payload = json.loads(completed.stdout)
    except json.JSONDecodeError:
        return []
    return [
        str(item.get("path"))
        for item in payload.get("errors", [])
        if item.get("code") == "ORPHAN_MARKDOWN" and item.get("path")
    ]


def _nearest_moc(wiki: Path, target: Path) -> Path | None:
    parent = target.parent
    while True:
        readme = parent / "README.md"
        if readme.is_file() and readme.resolve() != target.resolve():
            return readme
        if parent.resolve() == wiki.resolve():
            return None
        if parent.parent == parent:
            return None
        parent = parent.parent


def _ensure_reachability(layout: Layout) -> list[str]:
    """Link newly generated wiki files into the nearest MOC.

    Init/adopt can add generated files that the project's existing MOCs do not
    know about. The long-term wiki gate requires every Markdown file to be
    reachable from README.md, so init appends one link line per orphan to its
    nearest MOC. This is the only automatic edit init makes to project docs.
    """
    linked: list[str] = []
    for _ in range(4):
        orphans = _wiki_orphans(layout)
        if not orphans:
            break
        progressed = False
        for rel in orphans:
            target = layout.wiki / rel
            if not target.is_file():
                continue
            moc = _nearest_moc(layout.wiki, target)
            if moc is None:
                continue
            text = moc.read_text(encoding="utf-8-sig")
            link = posixpath.relpath(target.as_posix(), moc.parent.as_posix())
            if link in text:
                continue
            title = target.stem.replace("-", " ").strip() or target.stem
            util.write_text(moc, text.rstrip() + f"\n- [{title}]({link})：由 factory init 生成，待补充说明。\n")
            linked.append(f"{moc.relative_to(layout.work).as_posix()} -> {rel}")
            progressed = True
        if not progressed:
            break
    return linked


def _finish_init(
    work: Path,
    config: dict[str, Any],
    local: dict[str, Any],
    *,
    mode: str,
    answers: dict[str, Any],
    force: bool,
) -> int:
    work.mkdir(parents=True, exist_ok=True)
    config_mod.save_config(work, config)
    config_mod.save_local(work, local)
    layout = build_layout(work, config, local)
    renderer = Renderer(work, config, layout)
    plan = renderer.plan(force=force)
    hashes = renderer.apply(plan)
    skipped = [item.rel for item in plan.files if item.action == "skip"]
    _write_init_record(layout, config, mode=mode, answers=answers, hashes=hashes, skipped=skipped)
    _write_baseline(layout, config)
    gitignore_updated = _ensure_gitignore(work)
    linked = _ensure_reachability(layout)
    _write_state(layout, config, mode=mode, hashes=hashes)

    print(f"Initialized {work} ({mode}, repo mode {(config.get('repo') or {}).get('mode')})")
    print(f"  files written: {len(hashes)}; skipped: {len(skipped)}")
    if gitignore_updated:
        print("  .gitignore updated with .factory machine-state entries")
    if linked:
        print(f"  MOC links added for generated files: {len(linked)}")
    print(f"  config: {layout.factory_yaml}")
    print(f"  profile: {layout.workflow_profile}")
    print("Next: factory doctor --work .")
    return 0


def cmd_init(args: Any) -> int:
    work = Path(args.work).expanduser().resolve()
    if config_mod.config_path(work).is_file() and not args.force:
        util.echo_stderr(
            f"already initialized: {config_mod.config_path(work)} exists. "
            "Use factory doctor, or re-run with --force."
        )
        return 2
    answers = _load_answers(args.answers)
    config = config_mod.merge_answers(answers)
    _apply_identity(config, work)
    mode = args.mode or "new"
    if mode not in {"new", "adopt"}:
        util.echo_stderr("--mode must be new or adopt")
        return 2
    if mode == "adopt":
        if not work.is_dir():
            util.echo_stderr(f"adopt requires an existing work directory: {work}")
            return 2
        _apply_repo_topology(config, work, args.code, _detect_wiki_path(work, args.wiki))
    else:
        if args.code:
            _apply_repo_topology(config, work, args.code, args.wiki)
        elif args.wiki:
            _apply_repo_topology(config, work, None, args.wiki)
    _normalize_wiki_paths(config)
    try:
        config_mod.require_valid(config)
    except util.FactoryError as exc:
        util.echo_stderr(str(exc))
        return 2

    local = _build_local(args.python)
    layout = build_layout(work, config, local)
    try:
        plan = Renderer(work, config, layout).plan(force=args.force)
    except util.FactoryError as exc:
        util.echo_stderr(str(exc))
        return 2
    if args.dry_run:
        _print_plan(plan, args.json)
        return 0
    return _finish_init(work, config, local, mode=mode, answers=answers, force=args.force)

def cmd_adopt(args: Any) -> int:
    work = Path(args.work).expanduser().resolve()
    if not work.is_dir():
        util.echo_stderr(f"adopt requires an existing work directory: {work}")
        return 2
    if not args.code:
        util.echo_stderr("adopt requires --code <existing code repo path>")
        return 2
    answers = _load_answers(args.answers)
    config = config_mod.merge_answers(answers)
    _apply_identity(config, work)
    try:
        _apply_repo_topology(config, work, args.code, _detect_wiki_path(work, args.wiki))
        _normalize_wiki_paths(config)
        config_mod.require_valid(config)
    except util.FactoryError as exc:
        util.echo_stderr(str(exc))
        return 2

    local = _build_local(args.python)
    layout = build_layout(work, config, local)
    try:
        plan = Renderer(work, config, layout).plan(force=args.force)
    except util.FactoryError as exc:
        util.echo_stderr(str(exc))
        return 2
    if args.dry_run:
        _print_plan(plan, args.json)
        return 0
    return _finish_init(work, config, local, mode="adopt", answers=answers, force=args.force)


def cmd_upgrade(args: Any) -> int:
    work = Path(args.work).expanduser().resolve()
    try:
        config = config_mod.load_config(work)
        local = config_mod.load_local(work)
        config_mod.require_valid(config)
    except util.FactoryError as exc:
        util.echo_stderr(str(exc))
        return 2
    layout = build_layout(work, config, local)
    satisfied, reason = doctor_mod.version_satisfies(util.factory_version(), str((config.get("factory") or {}).get("version") or ""))
    if not satisfied:
        util.echo_stderr(f"factory version mismatch: {reason}. Update factory.version in .factory/factory.yaml first.")
        return 2
    try:
        plan = Renderer(work, config, layout).plan_upgrade()
    except util.FactoryError as exc:
        util.echo_stderr(str(exc))
        return 2
    if args.check or args.dry_run:
        _print_plan(plan, args.json)
        changed = [item for item in plan.files if item.action in {"create", "overwrite"}]
        return 0 if not changed else 1
    hashes = Renderer(work, config, layout).apply(plan)
    _write_state(layout, config, mode="upgrade", hashes=hashes)
    print(f"Upgraded {work}: {len(hashes)} file(s) refreshed")
    for item in plan.files:
        if item.action == "skip" and item.generated:
            print(f"  kept locally modified: {item.rel}")
    print("Next: factory doctor --work .")
    return 0


def cmd_status(args: Any) -> int:
    work = Path(args.work).expanduser().resolve()
    try:
        config = config_mod.load_config(work)
    except util.FactoryError as exc:
        util.echo_stderr(str(exc))
        return 2
    local = config_mod.load_local(work)
    layout = build_layout(work, config, local)
    state = config_mod.load_state(work)
    project = config.get("project") or {}
    repo = config.get("repo") or {}
    payload = {
        "work": str(work),
        "project": project.get("name"),
        "slug": project.get("slug"),
        "repo_mode": repo.get("mode"),
        "code_root": str(layout.code),
        "wiki_root": str(layout.wiki),
        "factory_version": util.factory_version(),
        "factory_root": str(layout.factory_root),
        "owners": [owner.get("id") for owner in config.get("owners") or []],
        "packs": (config.get("packs") or {}).get("enabled"),
        "initialized_at": state.get("created_at"),
        "updated_at": state.get("updated_at"),
        "mode": state.get("mode"),
    }
    if args.json:
        util.print_json(payload)
        return 0
    print(f"Project:  {payload['project']} ({payload['slug']})")
    print(f"Repo:     {payload['repo_mode']}  code={payload['code_root']}  wiki={payload['wiki_root']}")
    print(f"Factory:  {payload['factory_version']}  root={payload['factory_root']}")
    print(f"Owners:   {', '.join(payload['owners'] or []) or '-'}")
    print(f"Packs:    {', '.join(payload['packs'] or []) or '-'}")
    print(f"Init:     {payload['initialized_at']} ({payload['mode']})  updated={payload['updated_at']}")
    print("Next:     factory doctor --work .")
    return 0


def cmd_resolve(args: Any) -> int:
    work = Path(args.work).expanduser().resolve()
    try:
        config = config_mod.load_config(work)
    except util.FactoryError as exc:
        util.echo_stderr(str(exc))
        return 2
    local = config_mod.load_local(work)
    layout = build_layout(work, config, local)
    payload = layout.as_dict()
    payload["repo_mode"] = (config.get("repo") or {}).get("mode")
    payload["default_branch"] = (config.get("repo") or {}).get("default_branch")
    payload["factory_version"] = util.factory_version()
    if args.json:
        util.print_json(payload)
    else:
        for key, value in payload.items():
            print(f"{key}: {value}")
    return 0


def cmd_doctor(args: Any) -> int:
    work = Path(args.work).expanduser().resolve()
    result = doctor_mod.run_doctor(work, strict=args.strict, skip_gates=args.skip_gates)
    if args.json:
        util.print_json(result.as_dict())
        return doctor_mod.exit_code(result, args.strict)
    labels = {"ok": "OK  ", "warn": "WARN", "fail": "FAIL"}
    for check in result.checks:
        print(f"[{labels.get(check.level, check.level)}] {check.code}: {check.message}")
        if check.hint and check.level != "ok":
            print(f"       hint: {check.hint}")
    errors = len(result.errors)
    warnings = len(result.warnings)
    print(f"\nDoctor: {errors} error(s), {warnings} warning(s)")
    return doctor_mod.exit_code(result, args.strict)


def cmd_gate(args: Any) -> int:
    work = Path(args.work).expanduser().resolve()
    try:
        config = config_mod.load_config(work)
    except util.FactoryError as exc:
        util.echo_stderr(str(exc))
        return 2
    local = config_mod.load_local(work)
    layout = build_layout(work, config, local)
    code, out, err = doctor_mod.run_gate(layout, args.kind)
    if out:
        print(out)
    if err:
        util.echo_stderr(err)
    if args.json:
        util.print_json({"kind": args.kind, "exit_code": code, "stdout": out, "stderr": err})
    return code
